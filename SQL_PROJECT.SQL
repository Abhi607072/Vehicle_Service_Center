--1)FIND CUSTOMER NAME AND THEIR VEHICLE NUMBER THOSE HAVE MORE THAN 1 CAR.
SELECT *
FROM(SELECT DISTINCT C.CUSTOMER_NAME,COUNT(*)OVER(PARTITION BY CUSTOMER_NAME)AS CNT,V.VEHICLE_TYPE
FROM CUSTOMER C JOIN VEHICLES V
ON(C.CUSTOMER_ID = V.CUSTOMER_ID ))
WHERE CNT>1;
 
 
--2)FIND CUSTOMER NAME AND THEIR VEHICLE NUMBER
SELECT C.CUSTOMER_NAME,V.VEHICLE_NUMBER,V.VEHICLE_TYPE
FROM CUSTOMER C JOIN VEHICLES V
ON(C.CUSTOMER_ID = V.CUSTOMER_ID);
 
--3)FIND CUSTOMER NAME AND THEIR VEHICLE NUMBER AND DISPLAY ONLY THOSE CUSTOMERS THOSE HAVE SUV CAR, Luxury Car AND Sports Car.
SELECT C.CUSTOMER_NAME,V.VEHICLE_NUMBER,V.VEHICLE_TYPE
FROM CUSTOMER C JOIN VEHICLES V
ON(C.CUSTOMER_ID = V.CUSTOMER_ID)
WHERE V.VEHICLE_TYPE IN('SUV', 'Luxury Car','Sports Car'); 
 
--4)FIND CUSTOMER NAME AND THEIR VEHICLE NUMBER AND DISPLAY ONLY THOSE CUSTOMERS THOSE HAVE PASSING AT "MH12".
SELECT C.CUSTOMER_NAME,V.VEHICLE_NUMBER,V.VEHICLE_TYPE
FROM CUSTOMER C JOIN VEHICLES V
ON(C.CUSTOMER_ID = V.CUSTOMER_ID)
WHERE V.VEHICLE_NUMBER LIKE 'MH12%';

